# Simple Calculator

# Enter Numbers
num1= int(input("Enter 1st number:"))
num2= int(input("Enter 2nd number:"))
# Performing tasks in variable
add= num1 + num2
minus= num1 - num2
multi= num1* num2
divide= num1/num2
# Printing results
print(f"the sum of {num1} and {num2} is {add}")
print(f"the subtraction of {num1} and {num2} is {minus}")
print(f"the product of {num1} and {num2} is {multi}")
print(f"the division of {num1} and {num2} is {divide}")
